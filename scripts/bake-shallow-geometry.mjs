import fs from 'node:fs';
import crypto from 'node:crypto';
import {gzipSync} from 'node:zlib';
import {naturalBankSubstrate} from '../src/world/ShallowNaturalHabitat.js';

// Compile the existing static mesh factories without changing their sources,
// UVs, normals, groups, dimensions or collision arithmetic. No new assets.
const buffers=[],dedup=new Map();let bytes=0;
function array(value){
  const raw=Buffer.from(value.buffer,value.byteOffset,value.byteLength),key=value.constructor.name+':'+crypto.createHash('sha256').update(raw).digest('hex');
  if(dedup.has(key))return dedup.get(key);
  const padding=(8-bytes%8)%8;if(padding){buffers.push(Buffer.alloc(padding));bytes+=padding;}
  const row={type:value.constructor.name,offset:bytes,length:value.length};buffers.push(Buffer.from(raw));bytes+=raw.length;dedup.set(key,row);return row;
}
function geometry(g){
  g.computeBoundingBox();g.computeBoundingSphere();
  const attributes=Object.fromEntries(Object.entries(g.attributes).map(([key,a])=>[key,{...array(a.array),itemSize:a.itemSize,normalized:a.normalized}]));
  const row={attributes,index:g.index?array(g.index.array):null,groups:g.groups,userData:g.userData,box:[g.boundingBox.min.toArray(),g.boundingBox.max.toArray()],sphere:[g.boundingSphere.center.toArray(),g.boundingSphere.radius]};g.dispose();return row;
}
const geometries={};
for(const detail of ['near','distant'])for(let variant=0;variant<4;variant++){
  geometries[`substrate/${variant}/${detail}`]={substrate:geometry(naturalBankSubstrate(variant,detail))};
}
const blob=Buffer.concat(buffers),sha256=crypto.createHash('sha256').update(blob).digest('hex'),file='shallow-static-v1.bin';
fs.writeFileSync(`public/assets/${file}`,blob);
const compressed=gzipSync(blob,{level:9});
// A neutral OS marker keeps this transport identical on Windows and CI.
compressed[9]=255;
const transport={file:'shallow-static-v1-gzip.bin',encoding:'gzip',bytes:compressed.length};
fs.writeFileSync(`public/assets/${transport.file}`,compressed);
const manifest={version:1,file,bytes:blob.length,sha256,transport,geometries};
fs.writeFileSync('src/world/shallowGeometryManifest.js',`// Generated by scripts/bake-shallow-geometry.mjs from unchanged source factories.\nexport default ${JSON.stringify(manifest)};\n`);
console.log(`Compiled existing reef geometry: ${blob.length} bytes, ${Object.keys(geometries).length} families, unchanged substrate buffers.`);
console.log(`Lossless reef transport: ${compressed.length} bytes (${((1-compressed.length/blob.length)*100).toFixed(1)}% smaller).`);
