import fs from 'node:fs';
import {createShallowSample} from '../src/shallowSample.js';

// Finite sample authoring export. Runs the same exact support/clearance fit as
// runtime without a cached result; never bakes frame timing or animal motion.
const model=createShallowSample(55,{prepareCover:false});
const keys=['corals','grass','rubble','attachedReef','substrateSceneryRefit','livingCoverComposition','sandHabitat','scannedCoverComposition'];
const scenery=Object.fromEntries(keys.map(key=>[key,model[key]]));
fs.writeFileSync('src/world/shallowPreparedCover.js',`// Generated by scripts/bake-shallow-cover.mjs. Do not edit placements by hand.\nexport default ${JSON.stringify({seed:55,signature:model.coverInputSignature,rawSignature:model.coverRawInputSignature,scenery})};\n`);
console.log(`Prepared exact sample cover: ${model.corals.length} colonies; ${model.grass.length} grass groups; ${model.slopeHabitats.residents.length} slope residents.`);

fs.writeFileSync('src/world/shallowPreparedHabitats.js',`// Exact finite habitat footprint candidates, revalidated against actual support at startup.
export default ${JSON.stringify({signature:model.habitatInputSignature,footprints:model.slopeHabitats.footprints,primary:{signature:model.primaryHabitatSignature,sites:model.primaryHabitatSites}})};
`);
