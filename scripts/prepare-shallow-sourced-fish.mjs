// Finite CC0 source adaptation. Source topology, UVs and authored surface maps
// are preserved; this script does not generate a new fish or an animation rig.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import * as THREE from 'three';

const source = process.argv[2];
if (!source) throw new Error('Usage: node scripts/prepare-shallow-sourced-fish.mjs <downloaded-gltf-directory>');
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const gltfBytes = fs.readFileSync(path.join(source, 'BarramundiFish.gltf'));
const sourceJson = JSON.parse(gltfBytes), sourceBin = fs.readFileSync(path.join(source, 'BarramundiFish.bin'));
if (sha(gltfBytes) !== '15e2c26d308ef73f227655703ba88c37cf817e60e25229fab5cbfd0bf6888d2e' || sha(sourceBin) !== '5d6ca35ff4e498d84597956091cf5de8ce0f236cd9b8ebf48e19d372e4187112') throw new Error('Unverified source revision');
const output = 'public/assets/shallow-sourced-fish'; fs.mkdirSync(output, { recursive: true });
const primitive = sourceJson.meshes[0].primitives[0], packed = [], views = {};
let byteOffset = 0;
function readAccessor(index) {
  const a = sourceJson.accessors[index], view = sourceJson.bufferViews[a.bufferView];
  const components = { SCALAR:1, VEC2:2, VEC3:3, VEC4:4 }[a.type], bytes = a.componentType === 5123 ? 2 : 4;
  const values = a.componentType === 5123 ? new Uint16Array(a.count * components) : new Float32Array(a.count * components);
  for (let i=0;i<a.count;i++) for (let k=0;k<components;k++) {
    const offset = (view.byteOffset??0)+(a.byteOffset??0)+i*(view.byteStride??components*bytes)+k*bytes;
    values[i*components+k] = bytes === 2 ? sourceBin.readUInt16LE(offset) : sourceBin.readFloatLE(offset);
  }
  return {values,components};
}
const attrs = Object.fromEntries(Object.entries(primitive.attributes).map(([key,index])=>[key,readAccessor(index)]));
const position = attrs.POSITION.values, normal=attrs.NORMAL.values, tangent=attrs.TANGENT.values, uv=attrs.TEXCOORD_0.values;
const low=[Infinity,Infinity,Infinity], high=[-Infinity,-Infinity,-Infinity];
for(let i=0;i<position.length;i+=3)for(let k=0;k<3;k++){low[k]=Math.min(low[k],position[i+k]);high[k]=Math.max(high[k],position[i+k]);}
const length=high[2]-low[2], center=low.map((v,k)=>(v+high[k])/2);
// glTF node rotates raw geometry 180 degrees about Y. A further +90 degree
// rotation makes the raw -Z mouth +X and the raw +Z rounded tail -X.
// The source mouth UV u~.03 and tail UV u~.97 independently verify this choice.
const rotation=new THREE.Matrix4().makeRotationY(-Math.PI/2), vector=new THREE.Vector3();
for(let i=0;i<position.length;i+=3){
  vector.set(position[i]-center[0],position[i+1]-center[1],position[i+2]-center[2]).applyMatrix4(rotation).multiplyScalar(1/length);vector.toArray(position,i);
  vector.fromArray(normal,i).transformDirection(rotation).toArray(normal,i);
}
for(let i=0;i<tangent.length;i+=4)vector.fromArray(tangent,i).transformDirection(rotation).toArray(tangent,i);
const index=readAccessor(primitive.indices).values;
if(position.length/3!==2188||index.length/3!==3864)throw new Error('Source topology changed');
for(const [name,values,size] of [['position',position,3],['normal',normal,3],['tangent',tangent,4],['uv',uv,2],['index',index,1]]){
  const bytes=Buffer.from(values.buffer); views[name]={byteOffset,count:values.length/size,itemSize:size,type:values instanceof Uint16Array?'Uint16Array':'Float32Array'};packed.push(bytes);byteOffset+=bytes.length;
}
const binary=Buffer.concat(packed), encoded=binary.toString('base64');
fs.writeFileSync('src/world/ShallowSourcedFishData.js',`// Adapted Microsoft/Khronos BarramundiFish, CC0. Generated by prepare-shallow-sourced-fish.mjs.\nexport const sourcedFishViews=${JSON.stringify(views)};\nexport const sourcedFishBase64='${encoded}';\n`);
const python=process.env.SHALLOW_ASSET_PYTHON??'python';
const conversion=spawnSync(python,['-c',String.raw`
from pathlib import Path
from PIL import Image
import math, sys
source, target=map(Path,sys.argv[1:])
for original,name in [('BarramundiFish_baseColor.png','barramundi-basecolor.png'),('BarramundiFish_normal.png','barramundi-normal.png'),('BarramundiFish_occlusionRoughnessMetallic.png','barramundi-orm.png')]:
    with Image.open(source/original) as im:
        im.load(); im=im.resize((1024,1024),Image.Resampling.LANCZOS)
        if 'normal' in name:
            im=im.convert('RGB'); values=[]
            for rgb in im.getdata():
                x,y,z=(v/127.5-1 for v in rgb); length=math.sqrt(x*x+y*y+z*z) or 1
                values.append(tuple(max(0,min(255,round((v/length+1)*127.5))) for v in (x,y,z)))
            im.putdata(values)
        im.save(target/name,optimize=True)
`,source,output],{encoding:'utf8'});
if(conversion.status!==0)throw new Error(conversion.stderr||'Texture conversion failed');
const originalFiles=['BarramundiFish.gltf','BarramundiFish.bin','BarramundiFish_baseColor.png','BarramundiFish_normal.png','BarramundiFish_occlusionRoughnessMetallic.png'];
const sourceRoot='https://raw.githubusercontent.com/KhronosGroup/glTF-Sample-Assets/main/Models/BarramundiFish/glTF/';
const provenance={version:1,title:'Barramundi Fish',author:'Microsoft',publisher:'KhronosGroup glTF-Sample-Assets',license:'CC0-1.0',licenseUrl:'https://creativecommons.org/publicdomain/zero/1.0/',
  source:'https://github.com/KhronosGroup/glTF-Sample-Assets/blob/main/Models/BarramundiFish/README.md',
  scientificName:'Lates calcarifer',identityNote:'Publisher names Barramundi; not a fusilier, snapper or trevally replacement. No scan provenance claimed.',
  sourceFiles:originalFiles.map(file=>{const b=fs.readFileSync(path.join(source,file));return {file,download:sourceRoot+file,bytes:b.length,sha256:sha(b)};}),
  adaptations:['Preserve all 2188 source vertices, 3864 source triangles, UVs, tangent handedness and material texture channels.','Bake authored node pose plus axis alignment; raw -Z mouth becomes +X; centered neutral total length is 1.','Scale original maps to 1024 pixels using Lanczos; normalize reduced tangent-space normal vectors.','Tail wave is authored display motion in this project, not source skeletal animation or calibrated biomechanics.'],
  coordinates:{sourceBounds:{min:low,max:high},sourceForward:'raw -Z (mouth UV u~.03 vs distal tail u~.97)',axisTransform:'center source AABB, rotate raw Y -90 degrees, divide by raw Z length',unit:'neutral total length X=1'},
  motion:{sourceAnimations:0,type:'shared GPU tail-body shear',maxNormalizedOffset:.028,verticalOffset:0,amplitudeClamped:true},
  generatedData:{bytes:binary.length,sha256:sha(binary)},textures:['barramundi-basecolor.png','barramundi-normal.png','barramundi-orm.png'].map(file=>{const b=fs.readFileSync(path.join(output,file));return {file,width:1024,height:1024,bytes:b.length,sha256:sha(b)};})};
fs.writeFileSync(path.join(output,'provenance.json'),JSON.stringify(provenance,null,2));
